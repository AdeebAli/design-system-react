// Turns every `@example` in a component's TSDoc into a module under
// .generated/examples/, so `tsc` type-checks it (Spec 19). An example is a
// fenced tsx block: optional import lines, then one JSX expression. A name used
// as a JSX tag and not imported is imported from src/index.
import {
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { join, posix, relative, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const PACKAGE = '@adeebali/design-system-react';
const SKIPPED =
  /\.(test|test-d|stories|browser\.test|touch\.browser\.test)\.tsx?$|\.mdx$/;

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return entry.name === 'docs' ? [] : walk(path);
    return /\.tsx?$/.test(entry.name) && !SKIPPED.test(entry.name)
      ? [path]
      : [];
  });
}

const importedNames = (line) =>
  [...line.matchAll(/import\s+(?:type\s+)?\{([^}]*)\}/g)]
    .flatMap((match) => match[1].split(','))
    .map((name) =>
      name
        .trim()
        .replace(/^type\s+/, '')
        .split(/\s+as\s+/)
        .pop(),
    )
    .filter(Boolean);

/** Returns `{ written, errors }`. It clears `outDir` first. */
export function extractExamples(srcDir, outDir) {
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  const index = posix.join(
    ...relative(outDir, join(srcDir, 'index')).split(sep),
  );
  let written = 0;
  const errors = [];

  for (const file of walk(srcDir)) {
    const text = readFileSync(file, 'utf8');
    for (const block of text.matchAll(/\/\*\*[\s\S]*?\*\//g)) {
      if (!block[0].includes('@example')) continue;
      const where = relative(srcDir, file).split(sep).join('/');
      const owner = /^\s*export\s+(?:function|const)\s+([A-Za-z0-9_]+)/.exec(
        text.slice(block.index + block[0].length),
      );
      if (!owner) {
        errors.push(`${where}: an @example must be on an exported component`);
        continue;
      }
      const name = owner[1];
      if (block[0].split('@example').length > 2) {
        errors.push(`${name}: more than one @example`);
        continue;
      }
      const lines = block[0]
        .replace(/^\/\*\*/, '')
        .replace(/\*\/$/, '')
        .split('\n')
        .map((line) => line.replace(/^\s*\* ?/, ''));
      const body = lines.slice(
        lines.findIndex((l) => l.includes('@example')) + 1,
      );
      const fenced = /```(?:tsx|jsx)?\n([\s\S]*?)\n\s*```/.exec(
        body.join('\n'),
      );
      if (!fenced) {
        errors.push(`${name}: the @example must be a fenced \`\`\`tsx block`);
        continue;
      }
      const code = fenced[1].split('\n');
      const imports = code.filter((line) => /^\s*import\s/.test(line));
      const expression = code
        .filter((line) => !/^\s*import\s/.test(line))
        .join('\n')
        .trim()
        .replace(/;$/, '');

      const own = new Set();
      const kept = [];
      const fromPackage = new Set();
      for (const line of imports) {
        if (line.includes(`'${PACKAGE}'`) || line.includes(`"${PACKAGE}"`)) {
          for (const imported of importedNames(line)) fromPackage.add(imported);
        } else {
          kept.push(line.trim());
          for (const imported of importedNames(line)) own.add(imported);
        }
      }
      for (const [, tag] of expression.matchAll(/<\/?([A-Z][A-Za-z0-9]*)/g)) {
        if (!own.has(tag)) fromPackage.add(tag);
      }
      const names = [...fromPackage].sort();
      const header = [
        `// Generated by scripts/extract-examples.mjs from the @example of ${name} (${where}). Don't edit.`,
        ...(names.length > 0
          ? [`import { ${names.join(', ')} } from '${index}';`]
          : []),
        ...kept,
      ];
      const indented = expression
        .split('\n')
        .map((line) => `    ${line}`)
        .join('\n');
      writeFileSync(
        join(outDir, `${name}.tsx`),
        `${header.join('\n')}\n\nexport function Example() {\n  return (\n${indented}\n  );\n}\n`,
      );
      written += 1;
    }
  }
  return { written, errors };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const root = join(fileURLToPath(import.meta.url), '../..');
  const { written, errors } = extractExamples(
    join(root, 'src'),
    join(root, '.generated/examples'),
  );
  for (const error of errors) console.error(`extract-examples: ${error}`);
  if (errors.length > 0) process.exit(1);
  console.log(`extract-examples: ${written} examples`);
}
